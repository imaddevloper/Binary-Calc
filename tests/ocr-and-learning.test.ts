import { test } from 'node:test';
import assert from 'node:assert/strict';
import { scanImageForIPv4 } from '../src/services/ocr/index.ts';
import type { OcrEngine } from '../src/services/ocr/index.ts';
import { LESSON_COUNT, LESSON_IDS, LESSON_TRY } from '../src/features/learning/lessons.ts';
import { checkAnswer, generateChallenge } from '../src/core/challenges/index.ts';
import { parseIPv4 } from '../src/core/ipv4/index.ts';

const engine = (lines: string[] | Error | 'off'): OcrEngine => ({
  isSupported: () => lines !== 'off',
  recognize: async () => {
    if (lines instanceof Error) throw lines;
    return lines === 'off' ? [] : lines;
  },
});

test('OCR: valid address is returned as a candidate and re-validated', async () => {
  const r = await scanImageForIPv4('x', engine(['Router: 192.168.1.10']));
  assert.equal(r.status, 'ok');
  if (r.status === 'ok') {
    assert.equal(r.candidates.length, 1);
    assert.equal(r.candidates[0].suggested, '192.168.1.10');
    assert.equal(r.candidates[0].valid, true);
  }
});

test('OCR: confusable characters are suggested, flagged, never silently accepted', async () => {
  const r = await scanImageForIPv4('x', engine(['192.168.l.1O']));
  assert.equal(r.status, 'ok');
  if (r.status === 'ok') {
    const c = r.candidates[0];
    assert.equal(c.raw, '192.168.l.1O');
    assert.equal(c.suggested, '192.168.1.10');
    assert.equal(c.corrected, true);
    assert.equal(c.needsConfirmation, true);
  }
});

test('OCR: out-of-range candidates are marked invalid, not hidden', async () => {
  const r = await scanImageForIPv4('x', engine(['256.1.1.1']));
  assert.equal(r.status, 'ok');
  if (r.status === 'ok') {
    assert.equal(r.candidates[0].valid, false);
    assert.equal(r.candidates[0].needsConfirmation, true);
  }
});

test('OCR: several addresses give several candidates', async () => {
  const r = await scanImageForIPv4('x', engine(['10.0.0.1', 'gateway 172.16.0.254']));
  assert.equal(r.status, 'ok');
  if (r.status === 'ok') assert.equal(r.candidates.length, 2);
});

test('OCR: empty text, no address, unavailable engine and engine failure are distinct outcomes', async () => {
  assert.equal((await scanImageForIPv4('x', engine(['   ']))).status, 'no_text');
  assert.equal((await scanImageForIPv4('x', engine([]))).status, 'no_text');
  assert.equal((await scanImageForIPv4('x', engine(['hello world 12345']))).status, 'no_address');
  assert.equal((await scanImageForIPv4('x', engine('off'))).status, 'unavailable');
  assert.equal((await scanImageForIPv4('x', engine(new Error('boom')))).status, 'failed');
});

test('every lesson has a practice exercise generated by the validated engine', () => {
  assert.equal(LESSON_IDS.length, LESSON_COUNT);
  assert.equal(LESSON_COUNT, 17);
  for (const id of LESSON_IDS) {
    const spec = LESSON_TRY[id];
    assert.ok(spec, `lesson ${id} has no exercise`);
    for (let seed = 1; seed <= 25; seed++) {
      const ch = generateChallenge(spec.type, spec.difficulty, seed);
      // the stored answer must be accepted by the same checker the UI uses
      if (ch.answerBase === null) {
        assert.equal(checkAnswer(ch, ch.answer).status, 'correct');
        assert.equal(parseIPv4(ch.prompt).ok, ch.answer === 'valid');
      } else {
        assert.equal(checkAnswer(ch, ch.answer).status, 'correct', `${spec.type} seed ${seed}`);
      }
    }
  }
});

test('challenges: wrong and malformed answers are told apart', () => {
  const ch = generateChallenge('dec2bin', 'easy', 7);
  assert.equal(checkAnswer(ch, 'xyz').status, 'invalid_format');
  assert.equal(checkAnswer(ch, '').status, 'invalid_format');
  const wrong = ch.choices.find((c) => c !== ch.answer) as string;
  assert.equal(checkAnswer(ch, wrong).status, 'wrong');
});
